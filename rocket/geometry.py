def rocket_rise(t):
    """離昇からの上昇量 [mm]。t は動画の時刻 [s]。"""
    u = t - LAUNCH["t_liftoff"]
    if u <= 0:
        return 0.0
    return 0.5 * LAUNCH["accel"] * u * u + LAUNCH["jerk"] * u ** 3 / 6


