def ogive(r_base, length, n=24, r_tip=NOSE_R):
    """接線オジーブ(先端を丸める)。(r, h) の列。h は 0→length。"""
    rho = (r_base ** 2 + length ** 2) / (2 * r_base)
    pts = []
    for i in range(n + 1):
        h = length * i / n
        x = length - h                    # 先端からの距離
        r = sqrt(max(rho ** 2 - (length - x) ** 2, 0)) + r_base - rho
        pts.append((max(r, 0.0), h))
    # 先端を楕円弧で丸めて、ちょうど length で閉じる
    out = [p for p in pts if p[0] >= r_tip]
    h_last = out[-1][1]
    r_last = out[-1][0]
    for i in range(1, 7):
        a = (pi / 2) * i / 6
        out.append((r_last * cos(a), h_last + (length - h_last) * sin(a)))
    out[-1] = (0.0, float(length))
    return out


def core_profile():
    """機体(1段〜フェアリング)の外形。(半径, 機体下端からの高さ) の列、下から上へ。"""
