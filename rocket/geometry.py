def lattice_levels(h, panel):
    """格子塔のブレースの段の高さの列。"""
    n = int(h // panel)
    return [i * panel for i in range(n + 1)] + ([h] if h % panel else [])


def lightning_width(z):
    """避雷塔の高さ z での幅(先細り)。"""
    L = LIGHTNING
    return L["base_w"] + (L["top_w"] - L["base_w"]) * z / L["h"]


def catenary(p0, p1, z, sag, n=24):
    """2点間の架空地線(放物線近似)。3D の (x, y, z) の列。"""
    out = []
    for i in range(n + 1):
        u = i / n
        out.append((p0[0] + (p1[0] - p0[0]) * u, p0[1] + (p1[1] - p0[1]) * u,
                    z - 4 * sag * u * (1 - u)))
    return out


def light_aim(i):
    """照明塔 i の灯具がロケット(機体中央の高さ)を向く方位角と俯角 [rad]。"""
    from math import atan2
    x, y = LIGHT_TOWERS[i]
    zt = Z_BASE + ROCKET_LENGTH * 0.45
    dz = zt - LIGHT["h"]
    dist = sqrt(x * x + y * y)
    return atan2(-y, -x), atan2(dz, dist)


